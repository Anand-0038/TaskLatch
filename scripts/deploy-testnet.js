import { readFile, mkdir, writeFile } from 'node:fs/promises';
import solc from 'solc';
import { ContractFactory, JsonRpcProvider, Wallet, getAddress } from 'ethers';
import { requireArcTestnetRpc, ARC_TESTNET_CHAIN_ID, ARC_TESTNET_USDC, ARC_EXPLORER } from '../shared/evidence.js';

const rpc=requireArcTestnetRpc(process.env);
const expectedChainId=ARC_TESTNET_CHAIN_ID;
const token=getAddress(process.env.ARC_USDC_ADDRESS||ARC_TESTNET_USDC);
const secret=process.env.ARC_TESTNET_PRIVATE_KEY;
if(!secret)throw Error('Set ARC_TESTNET_PRIVATE_KEY in your local .env using a testnet-only wallet.');
const provider=new JsonRpcProvider(rpc);
const network=await provider.getNetwork();
if(network.chainId!==expectedChainId)throw Error('Refusing deployment: RPC is not Arc Testnet (chain ID 5042002).');
if(await provider.getCode(token)==='0x')throw Error('Configured Arc Testnet USDC address has no contract code.');
const signer=new Wallet(secret,provider);
if(await provider.getBalance(signer.address)===0n)throw Error('Deployer has no Arc Testnet USDC for gas.');
const source=await readFile(new URL('../contracts/ProofPayEscrow.sol',import.meta.url),'utf8');
const input={language:'Solidity',sources:{'ProofPayEscrow.sol':{content:source}},settings:{outputSelection:{'*':{'*':['abi','evm.bytecode.object']}}}};
const output=JSON.parse(solc.compile(JSON.stringify(input)));
const diagnostics=output.errors||[];
for(const d of diagnostics)if(d.severity==='error')console.error(d.formattedMessage);
if(diagnostics.some(d=>d.severity==='error'))process.exit(1);
const artifact=output.contracts['ProofPayEscrow.sol'].ProofPayEscrow;
const bytecode='0x'+artifact.evm.bytecode.object;
if(bytecode==='0x')throw Error('Compiler produced empty bytecode.');
const factory=new ContractFactory(artifact.abi,bytecode,signer);
const contract=await factory.deploy(token);
console.log('Deployment submitted:',contract.deploymentTransaction().hash);
await contract.waitForDeployment();
const address=await contract.getAddress();
await mkdir(new URL('../artifacts/',import.meta.url),{recursive:true});
await writeFile(new URL('../artifacts/ProofPayEscrow.abi.json',import.meta.url),JSON.stringify(artifact.abi,null,2));
console.log('Arc Testnet chain:',network.chainId.toString());
console.log('USDC:',token);
console.log('ProofPayEscrow:',address);
console.log('Explorer: '+ARC_EXPLORER+'/address/'+address);
console.log('Copy PROOFPAY_ESCROW_ADDRESS to your local .env. No mainnet calls were made.');
